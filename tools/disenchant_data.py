"""Write Disenchant.lua: which items can be disenchanted, and what each kind gives, from classic-db.

    python tools/disenchant_data.py <ClassicDB_*.sql.gz> [addon dir]

classic-db is the CMaNGOS community's Classic world database (GPL-3.0, https://github.com/cmangos/classic-db);
its Full_DB folder has the dump. Read from it: item_template (entry, DisenchantID) and disenchant_loot_template.
Chances are classic-db's, not measured in WoW Forever. Items it doesn't know get no disenchant value.
"""
import gzip
import sys
from pathlib import Path

DUMP = sys.argv[1]
OUT = Path(sys.argv[2] if len(sys.argv) > 2 else Path(__file__).resolve().parents[1]) / "Disenchant.lua"


def tuples(line):
    """The value tuples of one INSERT INTO ... VALUES (...),(...); line, as lists of strings."""
    i, n = line.index("VALUES") + 6, len(line)
    while i < n:
        while i < n and line[i] != "(":
            i += 1
        if i >= n:
            return
        i += 1
        vals, cur, quoted = [], [], False
        while i < n:
            c = line[i]
            if quoted:
                if c == "\\":
                    cur.append(line[i + 1])
                    i += 2
                    continue
                if c == "'":
                    quoted = False
                else:
                    cur.append(c)
                i += 1
                continue
            if c == "'":
                quoted = True
            elif c == ",":
                vals.append("".join(cur))
                cur = []
            elif c == ")":
                vals.append("".join(cur))
                i += 1
                break
            else:
                cur.append(c)
            i += 1
        yield vals


def columns(lines, table):
    """Column names of a CREATE TABLE, in order."""
    cols, inside = [], False
    for line in lines:
        if line.startswith(f"CREATE TABLE `{table}`"):
            inside = True
        elif inside:
            s = line.strip()
            if not s.startswith("`"):
                return cols
            cols.append(s.split("`")[1])
    return cols


with gzip.open(DUMP, "rt", encoding="utf-8", errors="replace") as f:
    lines = f.readlines()
icol = columns(lines, "item_template")
dcol = columns(lines, "disenchant_loot_template")
ENTRY, DEID = icol.index("entry"), icol.index("DisenchantID")
D_ENTRY, D_ITEM, D_CHANCE, D_GROUP, D_MIN, D_MAX = (dcol.index(c) for c in (
    "entry", "item", "ChanceOrQuestChance", "groupid", "mincountOrRef", "maxcount"))

items, loot = {}, {}
for line in lines:
    if line.startswith("INSERT INTO `item_template`"):
        for v in tuples(line):
            if int(v[DEID]) > 0:
                items[int(v[ENTRY])] = int(v[DEID])
    elif line.startswith("INSERT INTO `disenchant_loot_template`"):
        for v in tuples(line):
            if int(v[D_MIN]) < 0:
                sys.exit("references in disenchant_loot_template are not handled")
            loot.setdefault(int(v[D_ENTRY]), []).append(
                (int(v[D_ITEM]), float(v[D_CHANCE]), int(v[D_GROUP]), int(v[D_MIN]), int(v[D_MAX])))

# Chances as the core rolls them: group 0 rolls every entry on its own; in another group one entry drops, the ones
# with a chance first and the ones without sharing what is left equally.
groups, incomplete = {}, []
for gid, rows in sorted(loot.items()):
    out, whole = [], True
    for g in sorted({r[2] for r in rows}):
        part = [r for r in rows if r[2] == g]
        if g == 0:
            out += [(r[0], r[1], r[3], r[4]) for r in part]
            continue
        fixed = sum(r[1] for r in part if r[1] > 0)
        rest = [r for r in part if r[1] == 0]
        share = max(0.0, 100.0 - fixed) / len(rest) if rest else 0
        out += [(r[0], r[1] if r[1] > 0 else share, r[3], r[4]) for r in part]
        whole = whole and (fixed + share * len(rest)) >= 99.9
    # a group whose chances don't add up to 100% is missing rows in classic-db: leave that kind out
    if whole:
        groups[gid] = out
    else:
        incomplete.append(gid)
dropped = [i for i, d in items.items() if d in incomplete]
for i in dropped:
    del items[i]
if incomplete:
    print(f"left out incomplete kinds {incomplete} ({len(dropped)} items)")

missing = sorted({d for d in items.values() if d not in groups})
if missing:
    sys.exit(f"DisenchantIDs without loot: {missing}")

body = []
for gid, out in groups.items():
    body.append(f"[{gid}]={{" + ",".join(f"{{{m},{'%g' % round(p, 3)},{lo},{hi}}}" for m, p, lo, hi in out) + "},")
ids = "\n".join(f"[{i}]={d}," for i, d in sorted(items.items()))
OUT.write_text(
    "-- Generated by tools/disenchant_data.py from classic-db (CMaNGOS, GPL-3.0, https://github.com/cmangos/classic-db).\n"
    "-- Do not edit. DE_GROUPS: per disenchant kind, { material item ID, chance %, min, max } for each material.\n"
    "-- DE_ITEMS: item ID -> disenchant kind. Chances are classic-db's, not measured in WoW Forever.\n"
    "local _, ns = ...\n"
    "ns.DE_GROUPS = {\n" + "\n".join(body) + "\n}\n"
    "ns.DE_ITEMS = {\n" + ids + "\n}\n",
    encoding="utf-8",
    newline="\n",
)
print(f"{len(items)} items, {len(groups)} kinds -> {OUT} ({OUT.stat().st_size / 1e3:.0f} KB)")
