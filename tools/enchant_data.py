"""Write EnchantData.lua: the names of the enchants a player can put on gear, by SpellItemEnchantment ID.

    python -I tools/enchant_data.py --tables <ForeverMiner out/tables> [--addon <addon dir>]

From the WoW Forever client's SpellItemEnchantment table (ForeverMiner). Only lasting enchants (no duration, no
charges: weapon oils, poisons and sharpening stones wear off and never show on an auction) with a name. An item link
carries the enchant as its first field after the item ID ("item:2244:803:..."), and the addon names it from here.
"""
import argparse
import csv
from pathlib import Path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tables", required=True)
    ap.add_argument("--addon", default=str(Path(__file__).resolve().parents[1]))
    a = ap.parse_args()
    rows = {}
    with open(Path(a.tables) / "SpellItemEnchantment.csv", encoding="utf-8", newline="") as f:
        for r in csv.DictReader(f):
            name = (r.get("Name_lang") or "").strip()
            if not name or int(r.get("Duration") or 0) != 0 or int(r.get("Charges") or 0) != 0:
                continue
            rows[int(r["ID"])] = name
    out = [
        "-- Generated by tools/enchant_data.py from the WoW Forever client's SpellItemEnchantment table. Do not edit.",
        "-- Lasting enchants a player can put on gear, by ID (the first field after the item ID in an item link).",
        "local _, ns = ...",
        "ns.ENCHANTS = {",
    ]
    for i in sorted(rows):
        name = rows[i].replace("\\", "\\\\").replace('"', '\\"')
        out.append(f'[{i}]="{name}",')
    out.append("}")
    Path(a.addon, "EnchantData.lua").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(rows)} enchants")


if __name__ == "__main__":
    main()
